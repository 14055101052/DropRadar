async function migrateStorage({ pool, sqlite }) {
  if (pool) {
    await pool.query(`CREATE TABLE IF NOT EXISTS schema_migrations (
      version INTEGER PRIMARY KEY,
      applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )`);

    for (const migration of MIGRATIONS) {
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const applied = await client.query(
          "SELECT 1 FROM schema_migrations WHERE version = $1",
          [migration.version]
        );
        if (applied.rowCount === 0) {
          for (const statement of migration.postgres) await client.query(statement);
          await client.query(
            "INSERT INTO schema_migrations (version) VALUES ($1)",
            [migration.version]
          );
        }
        await client.query("COMMIT");
      } catch (error) {
        await client.query("ROLLBACK");
        throw error;
      } finally {
        client.release();
      }
    }
    await pool.query("SELECT 1");
    return;
  }

  sqlite.pragma("journal_mode = WAL");
  sqlite.pragma("foreign_keys = ON");
  sqlite.exec(`CREATE TABLE IF NOT EXISTS schema_migrations (
    version INTEGER PRIMARY KEY,
    applied_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
  )`);

  for (const migration of MIGRATIONS) {
    const apply = sqlite.transaction(() => {
      const applied = sqlite.prepare(
        "SELECT 1 FROM schema_migrations WHERE version = ?"
      ).get(migration.version);
      if (applied) return;
      for (const statement of migration.sqlite) sqlite.exec(statement);
      sqlite.prepare(
        "INSERT INTO schema_migrations (version) VALUES (?)"
      ).run(migration.version);
    });
    apply.immediate();
  }
}

